"""Download a published data tier and check it arrived intact.

The wheel carries no HDF5 files and no search index — together they are hundreds
of megabytes — so a fresh install can run ``gui --demo`` and nothing else. This
module is how it gets real data.

**Tiers are fetched whole, never piecemeal.** A tier names its HDF5 files *and*
the index built over them, and :func:`fetch_tier` takes both or neither. An
index without its data is the worst failure this package has: a SQLite index is
self-contained, so it keeps answering searches across every molecule it knows
while every hit fails to open. Refusing to create that state is cheaper than
detecting it later.

Every file is checksummed. A truncated download that still parses as HDF5 is
worse than one that does not, because it fails as wrong numbers rather than as
an error.
"""

from __future__ import annotations

import hashlib
import json
import shutil
import urllib.error
import urllib.request
from collections.abc import Iterator
from dataclasses import dataclass
from importlib import resources
from pathlib import Path
from typing import Any

#: Manifest shipped in the wheel, generated by ``scripts/make_release_manifest.py``.
MANIFEST_RESOURCE = "releases.json"

#: Read size for hashing and streaming. Large enough that a 600 MB file is not
#: 150k syscalls, small enough to stay out of the way.
CHUNK_BYTES = 1 << 20


class FetchError(RuntimeError):
    """A tier could not be fetched, or arrived damaged."""


@dataclass(frozen=True)
class Artifact:
    """One downloadable file.

    Attributes:
        name: Filename, also the release-asset name.
        subdir: Where it lands under the destination root (``raw`` or ``cache``).
        size_bytes: Expected size, used for progress and a cheap pre-check.
        sha256: Expected hex digest.
    """

    name: str
    subdir: str
    size_bytes: int
    sha256: str

    def destination(self, root: Path) -> Path:
        return root / self.subdir / self.name


@dataclass(frozen=True)
class Tier:
    """A data release: HDF5 files plus the index built over exactly those files.

    Attributes:
        key: Short name used on the command line, e.g. ``1pct``.
        description: One line shown when listing tiers.
        base_url: Prefix each artifact name is appended to.
        artifacts: Everything in the tier, data and index together.
    """

    key: str
    description: str
    base_url: str
    artifacts: tuple[Artifact, ...]

    @property
    def total_bytes(self) -> int:
        return sum(a.size_bytes for a in self.artifacts)

    def url_for(self, artifact: Artifact) -> str:
        return f"{self.base_url.rstrip('/')}/{artifact.name}"


def _manifest_text() -> str:
    """Read the shipped manifest, falling back to the source tree.

    Same two-step as :func:`rpfr_visualizer.io.search.names._load_synonym_seed`: an
    editable install without package data still has the file on disk.
    """
    try:
        root = resources.files("rpfr_visualizer.data")
        return (root / MANIFEST_RESOURCE).read_text(encoding="utf-8")
    except (FileNotFoundError, OSError, TypeError, AttributeError):
        path = Path(__file__).resolve().parent / "data" / MANIFEST_RESOURCE
        if not path.exists():
            raise FetchError(
                "No release manifest found. This install is missing "
                f"rpfr_visualizer/data/{MANIFEST_RESOURCE}."
            ) from None
        return path.read_text(encoding="utf-8")


def load_manifest(text: str | None = None) -> dict[str, Tier]:
    """Parse the release manifest into tiers.

    Args:
        text: Manifest JSON. Defaults to the copy shipped in the wheel.

    Returns:
        Tiers by key.

    Raises:
        FetchError: If the manifest is malformed or empty.
    """
    try:
        raw: Any = json.loads(text if text is not None else _manifest_text())
    except json.JSONDecodeError as exc:  # pragma: no cover - corrupt install
        raise FetchError(f"Release manifest is not valid JSON: {exc}") from exc

    tiers: dict[str, Tier] = {}
    for key, body in (raw.get("tiers") or {}).items():
        artifacts = tuple(
            Artifact(
                name=item["name"],
                subdir=item["subdir"],
                size_bytes=int(item["size_bytes"]),
                sha256=item["sha256"],
            )
            for item in body.get("artifacts", ())
        )
        if not artifacts:
            raise FetchError(f"Tier {key!r} lists no artifacts.")
        tiers[key] = Tier(
            key=key,
            description=body.get("description", ""),
            base_url=body["base_url"],
            artifacts=artifacts,
        )
    if not tiers:
        raise FetchError("Release manifest lists no tiers.")
    return tiers


def sha256_of(path: Path) -> str:
    """Hex digest of *path*, read in chunks so file size does not matter."""
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(CHUNK_BYTES), b""):
            digest.update(chunk)
    return digest.hexdigest()


def verify(artifact: Artifact, root: Path) -> bool:
    """Whether *artifact* is present under *root* and matches its checksum.

    Size is checked first: it is a ``stat`` and rules out most damage without
    reading hundreds of megabytes.
    """
    path = artifact.destination(root)
    if not path.exists():
        return False
    if path.stat().st_size != artifact.size_bytes:
        return False
    return sha256_of(path) == artifact.sha256


def _download(url: str, target: Path, expected_bytes: int) -> None:
    """Stream *url* to *target*, via a .part file so a partial write is never
    mistaken for a finished one."""
    part = target.with_suffix(target.suffix + ".part")
    part.parent.mkdir(parents=True, exist_ok=True)
    try:
        with urllib.request.urlopen(url) as response, part.open("wb") as out:  # noqa: S310
            shutil.copyfileobj(response, out, CHUNK_BYTES)
    except urllib.error.URLError as exc:
        part.unlink(missing_ok=True)
        raise FetchError(f"Could not download {url}: {exc.reason}") from exc

    written = part.stat().st_size
    if written != expected_bytes:
        part.unlink(missing_ok=True)
        raise FetchError(
            f"{target.name}: expected {expected_bytes} bytes, received {written}. "
            "The download was truncated; try again."
        )
    part.replace(target)


def fetch_tier(
    tier: Tier,
    root: Path,
    *,
    force: bool = False,
    progress: bool = True,
) -> Iterator[tuple[Artifact, str]]:
    """Download and verify every artifact in *tier* under *root*.

    Yields as it goes rather than returning at the end, so a caller can report
    a 534 MB fetch while it happens.

    Args:
        tier: What to fetch. Data and index together, always.
        root: Destination; artifacts land in ``root/raw`` and ``root/cache``.
        force: Re-download even when a local copy already verifies.
        progress: Unused placeholder for a future progress bar; the caller
            currently reports per-file.

    Yields:
        ``(artifact, status)`` where status is ``"present"``, ``"fetched"``.

    Raises:
        FetchError: On a failed download or a checksum mismatch. Nothing
            partially downloaded is left behind under its final name.
    """
    del progress  # reported by the caller, per file
    for artifact in tier.artifacts:
        target = artifact.destination(root)
        if not force and verify(artifact, root):
            yield artifact, "present"
            continue

        _download(tier.url_for(artifact), target, artifact.size_bytes)

        digest = sha256_of(target)
        if digest != artifact.sha256:
            target.unlink(missing_ok=True)
            raise FetchError(
                f"{artifact.name}: checksum mismatch.\n"
                f"  expected {artifact.sha256}\n"
                f"  got      {digest}\n"
                "The file was removed rather than left in place to be trusted."
            )
        yield artifact, "fetched"


def human_bytes(count: int) -> str:
    """Format a byte count the way a download prompt should read."""
    size = float(count)
    for unit in ("B", "KB", "MB", "GB"):
        if size < 1024 or unit == "GB":
            return f"{size:.0f} {unit}" if unit == "B" else f"{size:.1f} {unit}"
        size /= 1024
    return f"{size:.1f} GB"  # pragma: no cover - unreachable, loop returns


